	LOGICAL*2 RISULT
C      COMMON/SYSTEM/IN,IO,KDOS,MDOS,LDOS,NDOS,NUOVER,NOUTP3,KCONV
	INCLUDE 'GENERAL.FI'
C------------------------------
	INTEGER*2 LR(3),LC(3),JJJ,I,J,N1,K,IT,JT,K1,K2,KKK,I1
      REAL  Aloc(3,4),SG
C------------------------------
	RISULT=.TRUE.
      SG=1.E-20
      N1=N+1
      DO 15  I=1,Mloc
      DO 15 J=1,N1
      IF(J.GE.N1)GO TO 14
      Aloc(I,J)=COEF(I,J)
