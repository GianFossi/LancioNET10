      SUBROUTINE COUPS(NOZ1,NOZ2,IC,overFIT1,overFIT2,overFIT3,
     x	ISSUE1,ISSUE2,FILE,NOZAD1,NOZAD2)
      USE mTYPINV
	USE DFWIN
	IMPLICIT NONE
!DEC$ ATTRIBUTES DLLEXPORT::COUPS
	TYPE(NOZZLE)::NOZ1
	TYPE(NOZZLE)::NOZ2
	TYPE(NOZZLE)::NOZ(2)
	TYPE(NozzAd)::NOZAD1,NOZAD2,NOZAD(2)
	TYPE(ASMERES)::ISSUE1,ISSUE2,ISSUE(2)
	TYPE(Str50)::FILE
	REAL*4 overFIT1,overFIT2,overFIT3
C
C.....COMPENSAZIONE APERTURE ACCOPPIATE LONG. SU FONDI SFERICI
C     SECONDO ASME VIII D.2 AD 500-540.
C     AGGIUNTO COMPENSAZIONE DI BOCCHELLI NON RADIALI
C     IND = INDICE DEL TIPO DI FONDO
C     ITSH=INDICE SE L'APERTURA E' TANGENZIALE
C     DD3XL=RAGGIO ZONA SFERICA
C
C
C     Rev.4A - 21/01/98 - 1) Modificato controllo su d/D(basato 
C                            ora sui diam. nominali anziche' cor-
C         CD                 rosi
C                         2) Agggiunta conversione SI

C      REAL J1,J2,J3,J4,J5,J6,J7,J8,J9
      REAL*4 DOO(2),ITSH(2),TNNF(2),TNNF1(2)
	REAL*4 ShThNzAr1,TCORR,DL,RAGGIO,RM,RN,ALFA1,ALFA2,EPS
	REAL*4 TEST1,XL1,XL2,SOMMAL,DX,DE1,DE2,FITL,TESTN,XL4,L3A
	REAL*4 LS
	INTEGER*4 IC,I,IL3,xMESS
	CHARACTER*120 DOMANDA
	IC=0
      ShThNzAr=TD3
	ShThNzAr1=NOZ1%ShThkNozArea/MM
	IF(ShThNzAr1.GT.ShThNzAr/2.AND.ShThNzAr1.LT.ShThNzAr*2)
     *   ShThNzAr=ShThNzAr1
      ITSH(1)=0
      ITSH(2)=0
C
C     CALCOLA LO SPESSORE MINIMO SENZA CORROSIONE
C            era TS=TS-C3
      TCORR=TD3-C3
C      WRITE(*,*)'DISTANCE BETWEEN TWO NOZZLE (mm)'
C      READ(*,*)DL
	NOZ1%Risult=0
	NOZ2%Risult=0
	NOZ(1)=NOZ1
	NOZ(2)=NOZ2
	NOZAD(1)=NOZAD1
	NOZAD(2)=NOZAD2
	ISSUE(1)=ISSUE1
	ISSUE(2)=ISSUE2
	CALL INTERF(NOZ1,NOZ2,IC,DL,RAGGIO)
	IF(IC.GT.0)GOTO 121
      DL=DL/MM
      DO 501 I=1,2
	CALL VediRegola(NOZ(I),NOZAD(I))
C      WRITE(*,*)'INSIDE DIAMETER OF',I,' ø  OPENING  (mm)'
      DOO(I)=NOZ(I)%DiIn
      DOO(I)=DOO(I)/MM
      DTT(I)=DOO(I)
C      WRITE(*,*)I,' ø NOZZLE NOMINAL THICKNESS       (mm)'
      TNNF(I)=NOZ(I)%HX
	IF(TNNF(I).EQ.0.)TNNF(I)=NOZ(I)%Spess
C      READ(*,*)TNNF(I)
      TNNF(I)=TNNF(I)/MM
C      WRITE(*,*)I,' ø NOMINAL THICKNESS OF CONNECTING PIPE (mm)'
      TNNF1(I)=NOZ(I)%Spess
      TNNF1(I)=TNNF1(I)/MM
	LXdisp=NOZ(I)%LXdisp
	CorrNoz(I)=NOZ(I)%CorrA
	IF(NOZ(I)%ONn.GT.CorrNoz(I))CorrNoz(I)=NOZ(I)%ONn
501   CorrNoz(I)=CorrNoz(I)/MM
	IF(DL.LT.(DOO(1)+DOO(2)+TNNF(1)+TNNF(2))/2)THEN
	   IC=3
         overFIT3=DL*MM
	   GOTO 121
	ENDIF
      DO 500 I=1,2
C      WRITE(*,*)'THE NOZZLE IS TANGENTIAL TO SFERICAL HEAD Y/N'
C      READ(*,1)Y
      IF(IC.EQ.-1)THEN
C       WRITE(*,*)' DISTANCE NOZZLE AXES FROM C.L. AXES OF'
C       WRITE(*,*)' SPHERICAL HEAD (mm)'
       XLL=NOZ(I)%DCL
       XLL=XLL/MM
       RM=DD3XL+C3+TCORR*0.5
       RN=(DOO(I)+2.0*CorrNoz(I))*0.5
       ALFA1=ACOS((XLL+RN)/RM)
       ALFA2=ACOS((XLL-RN)/RM)
       ALFA=ALFA2-ALFA1
       DOE=2.0*RM*SQRT(1-(COS(ALFA/2.0))**2)
       DOO(I)=DOE
       ITSH(I)=1
      ENDIF
C      TEST=(DOO(I)+2.0*C3)/(2.*DD3XL+2.0*C3)
C      IF(TEST.GT.0.50)GOTO 99
      EPS=0.01
!	WRITE(DOMANDA,'(''DD3XL''F12.3,A1)')DD3XL,char(0)
!      xMESS = MessageBoxEx(NULL,DOMANDA,'ISA'C,MB_YESNO+
!     1	                                 +MB_ICONQUESTION+
!     2                                     +MB_SETFOREGROUND,
!     3                     LANG_ITALIAN)
      TEST=(DOO(I))/(2.*DD3XL)
      IF(TEST.GT.(0.50+EPS))THEN
C99    CONTINUE
C      WRITE(*,*)'d/D > 0.50 USE ASME CODE APPENDIX 4 OR 5 '
C	 NOZ(I)%Risult=-1
C	 GOTO 121
	ENDIF
      RRM=(2.*DD3XL+C3+TD3)*0.5
      TEST1=0.2*SQRT(RRM*(TD3-C3))
      IF((DOO(I)+2.*CorrNoz(I)).LT.TEST1)THEN
C       WRITE(*,*)'SINGLE OPENING HAS A DIAMETER < 0.2*SQRT(Rm*T)'
C       WRITE(*,*)'YOU WANT REINFORCEMENT THE OPENING Y/N'
C	  NOZ(I)%Risult=-2
C	  GOTO 121
      ENDIF
500   CONTINUE
C
C     CALCOLO LIMITI DI RINFORZO LUNGO IL MANTELLO SECONDO AD 540.1
C
      TKN=TNNF(1)
      DL1=DOO(1)+2.*CorrNoz(1)
      DL2=0.5*(DOO(1)+2.*CorrNoz(1))+(TD3-C3)+(TKN-CorrNoz(1))
C
C     CALCOLA LA L PER IL PRIMO BOCCHELLO
C
      XL1=AMAX1(DL1,DL2)
      TKN=TNNF(2)
      DL3=DOO(2)+2.*CorrNoz(2)
      DL4=0.5*(DOO(2)+2.*CorrNoz(2))+(TD3-C3)+(TKN-CorrNoz(2))
C
C     CALCOLA LA L PER IL SECONDO BOCCHELLO
C
      XL2=AMAX1(DL3,DL4)
C
C     SOMMA LE DUE L CALCOLATE
C
	SOMMAL=XL1+XL2
C
C     CALCOLA LA LUNGHEZZA DI INTERFERENZA
C
      DX=ABS(SOMMAL-DL)
C
C     TEST SE LE APERTURE INTERFERISCONO
C
      IF(DL.GT.SOMMAL)THEN
C       WRITE(*,*)' THE OPENINGS DO NOT OVERLAP'
       overFIT1=XL1*MM
C       WRITE(*,*)' LIMIT OF REINFORCEMENT ALONG SHELL FOR FIRST NOZZLE:'
C       WRITE(*,*)' L = ',XL1,'  inch = ',FIT,' mm'
       overFIT2=XL2*MM
C       WRITE(*,*)' LIMIT OF REINFORCEMENT ALONG SHELL FOR SECO. NOZZLE:'
C       WRITE(*,*)' L = ',XL2,'  inch = ',FIT,' mm'
       overFIT3=DL*MM
C       WRITE(*,*)' DISTANCE FROM AXES OF TWO NOZZLE:'
C       WRITE(*,*)' DL = ',DL,'  inch = ',FIT,' mm'
C       WRITE(*,*)' CONTINUE WITH NORMAL CALCULATION OF OPENING'
C       WRITE(*,*)' AND GIVE AGAIN THE SAME INPUT'
       IC=-2
	GOTO 121
      ENDIF
C      IF(IC.EQ.1)GOTO 100
C
C     SE LE APERTURE INTERFERISCONO LIMITA LA L
C
      IF(DL.LT.SOMMAL)THEN
C
C     CALCOLA LE NUOVE L E MEMORIZZA LE VECCHIE IN FITL1&FITL2
C
       FITL1=XL1
       FITL2=XL2
       XL1=XL1-DX/2.
       XL2=XL2-DX/2.
       DE1=DOO(1)/2.
       DE2=DOO(2)/2.
       overFIT1=XL1*MM
       overFIT2=XL2*MM
       overFIT3=DL*MM
C
C      CONTROLLA CHE I LIMITI DI RINFORZO SUPERINO IL FILO ESTERNO
C      DEL BOCCHELLO
C
		IF(XL1.LT.DE1)NOZ(1)%Risult=-8
		IF(XL2.LT.DE2)NOZ(2)%Risult=-8
C       IF(XL1.LT.DE1 .OR. XL2.LT.DE2)
C     X WRITE(*,*)'WARNING*** LIMIT OF REINFORCEMENT WITHIN De ON NOZZLE'
      IC=-1
	IF(XL1.LT.DE1.OR.XL2.LT.DE2) IC=3
	ENDIF
121	CLOSE(6)
	NOZ1=NOZ(1)
	NOZ2=NOZ(2)
	ISSUE1=ISSUE(1)
	ISSUE2=ISSUE(2)
      RETURN
      END
C*****************************************************************************
	SUBROUTINE INTERF(NOZ1,NOZ2,I,DIST,RAGGIO)
      USE mTYPINV
	IMPLICIT NONE
	TYPE(NOZZLE)::NOZ1
	TYPE(NOZZLE)::NOZ2
	REAL*4 DIST,RAGGIO,AZIMUT1,ANOMAL1,posX1,posY1,posZ1
	REAL*4 AZIMUT2,ANOMAL2,posX2,posY2,posZ2,ANG
	INTEGER*4 I
C----------------------------------------------------
	CALL RAGGIOCAL(RAGGIO)
	CALL POSIZ(NOZ1,AZIMUT1,ANOMAL1,RAGGIO,I)
	IF(I.GT.0)RETURN
	posX1=RAGGIO*COS(ANOMAL1)*SIN(AZIMUT1)
	posY1=RAGGIO*SIN(ANOMAL1)*SIN(AZIMUT1)
	posZ1=RAGGIO*COS(AZIMUT1)
	CALL POSIZ(NOZ2,AZIMUT2,ANOMAL2,RAGGIO,I)
	IF(I.GT.0)THEN
	   IF(I.EQ.1)I=11
	   RETURN
	ENDIF
	posX2=RAGGIO*COS(ANOMAL2)*SIN(AZIMUT2)
	posY2=RAGGIO*SIN(ANOMAL2)*SIN(AZIMUT2)
	posZ2=RAGGIO*COS(AZIMUT2)
	DIST=SQRT((posX1-posX2)**2+(posY1-posY2)**2+(posZ1-posZ2)**2)
	ANG=2*ASIN(DIST/2/RAGGIO)
	DIST=RAGGIO*ANG
	RAGGIO=RAGGIO-TD3*MM/2
	RETURN
	END
C*************************************************************
	SUBROUTINE RAGGIOCAL(RAGGIO)
	USE mTYPINV
	SELECT CASE(INDFON)
	CASE(1)
	    RAGGIO=DD3*MM/2
	CASE(2)
	    RAGGIO=CROWN*MM
	CASE(3)
	    RAGGIO=.85*DD3*MM
	END SELECT
	RAGGIO=RAGGIO+TD3*MM/2 !correzione Villa/Presciuttini 10/06/2002
	DD3XL=RAGGIO/MM
	RETURN
	END
	SUBROUTINE POSIZ(NOZ,AZIMUT,ANOMAL,Raggio,I)
      USE mTYPINV
	TYPE(NOZZLE)::NOZ
	  I=0 
        IF(NOZ%DCL.EQ.0.AND.NOZ%DTL.EQ.0.AND.NOZ%beta.EQ.0)THEN
c	   'assiale centrato
           AZIMUT=0
	     ANOMAL=0
        ELSEIF(NOZ%DCL.EQ.0.AND.NOZ%DTL.EQ.0) THEN
c	   'radiale rispetto al fondo
           AZIMUT=NOZ%beta*GreekPI/180
	     ANOMAL=NOZ%Anomal*GreekPI/180
        ELSEIF(NOZ%DCL.EQ.0.AND.NOZ%beta.EQ.0) THEN
c	   'radiale rispetto al cilindro
           IF(INDFON.EQ.1)THEN
      	    ANOMAL=NOZ%Anomal*GreekPI/180
	        AZIMUT=ACOS(NOZ%DTL/RAGGIO)
	     ELSE
              I=1
           ENDIF
        ELSEIF(NOZ%DTL.EQ.0.AND.NOZ%beta.EQ.0) THEN 
c	  'assiale decentrato
	     ANOMAL=NOZ%Anomal*GreekPI/180
	     I=-1
	  IF(NOZ%DCL>=Raggio)THEN
	     I=2
	  ELSE 
	     AZIMUT=ASIN(NOZ%DCL/Raggio)
	  ENDIF
        ENDIF
	RETURN
	END