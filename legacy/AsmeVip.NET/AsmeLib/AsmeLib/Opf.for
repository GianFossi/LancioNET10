      SUBROUTINE TEST1(ISN)
C
C     ROUTINE DI CALCOLO SECONDO ASME VIII D.2 AD-211
C     ALFA MINORE DI 30 GRADI
C     ISN=VARIABILE DI CONTROLLO SE E' SODDISFATTO IL GRAFICO
C     DI FIG. AD-211.1
C
	USE mTYPINV
C.....SETTA ISN IN MANIERA CHE LA VERIFICA NON E' SODDISFATTA
C
      ISN=1
C.....RETTA 1
      IF(ALFA.LT.15.0 .AND. ALFA.GE.11.0) THEN
       PS=4.1666675E-4*ALFA-2.58333425E-3
C......SE E' SODDISFATTO SETTA ISN=0
       IF(TEST.GE.PS)ISN=0
      ENDIF
C.....RETTA 2
      IF(ALFA.LT.17.5 .AND. ALFA.GE.15.0) THEN
       PS=4.76132E-4*ALFA-3.475313E-3
C......SE E' SODDISFATTO SETTA ISN=0
       IF(TEST.GE.PS)ISN=0
      ENDIF
C.....RETTA 3
      IF(ALFA.LT.20.0 .AND. ALFA.GE.17.5) THEN
       PS=9.4608E-4*ALFA-0.0116994
C......SE E' SODDISFATTO SETTA ISN=0
       IF(TEST.GE.PS)ISN=0
      ENDIF
C.....RETTA 4
      IF(ALFA.LT.25.0 .AND. ALFA.GE.20.0) THEN
       PS=4.127E-4*ALFA-1.03178E-3
C......SE E' SODDISFATTO SETTA ISN=0
       IF(TEST.GE.PS)ISN=0
      ENDIF
C.....RETTA 5
      IF(ALFA.LT.30.0 .AND. ALFA.GE.25.0) THEN
       PS=4.127E-4*ALFA-1.03178E-3
C......SE E' SODDISFATTO SETTA ISN=0
       IF(TEST.GE.PS)ISN=0
      ENDIF
      RETURN
      END
C----------------------------------------------------------------------
      SUBROUTINE TEST2(ISN,Q,RRLC,RRL)
C
C     ROUTINE DI CALCOLO SECONDO ASME VIII D.2 AD-211
C     ALFA MINORE DI 30 GRADI
C     ISN=VARIABILE DI CONTROLLO SE E' SODDISFATTO IL GRAFICO
C     DI FIG. AD-211.1 E DA IL VALORE Q SE E' RICHIESTO
C     IL RINFORZO DEL CONO
C
	USE mTYPINV
      Q=0.0
      IF(ISN.EQ.0)GOTO 999
C.....RETTA 1 E 2 CON ALFA MINORE DI 10 GRADI
      IF(ALFA.LE.10) THEN
       IF(TEST.LT.0.0012 .AND. TEST.GE.0.001) THEN
        Q=-350.*TEST+1.52
       ENDIF
       IF(TEST.LT.0.0015 .AND. TEST.GE.0.0012) THEN
        Q=-266.66667*TEST+1.42
       ENDIF
       IF(TEST.GT.0.0015)Q=1.02
      ENDIF
C.....RETTA 1 E 2 CON ALFA COMPRESO TRA 10 E 15 GRADI
      IF(ALFA.LT.15.0 .AND. ALFA.GT.10.0) THEN
       IF(TEST.LT.0.0012 .AND. TEST.GE.0.001) THEN
        Q1=-350.*TEST+1.52
       ENDIF
       IF(TEST.LT.0.0015 .AND. TEST.GE.0.0012) THEN
        Q1=-266.66667*TEST+1.42
       ENDIF
       IF(TEST.GT.0.0015)Q1=1.02
       IF(TEST.LT.0.002 .AND. TEST.GE.0.001) THEN
        Q2=-300.*TEST+1.81
       ENDIF
       IF(TEST.LT.0.0034 .AND. TEST.GE.0.002) THEN
        Q2=-114.2857143*TEST+1.438571429
       ENDIF
       IF(TEST.GE.0.0034)Q2=1.05
C......CALCOLA IL VALORE Q IN FUNZIONE DEL VALORE DI ALFA
       DX=(Q2-Q1)/5.0
       Q=ALFA*DX+Q1
      ENDIF
C.....RETTA 2 E 3 CON ALFA COMPRESO TRA 15 E 20 GRADI
      IF(ALFA.LT.20.0 .AND. ALFA.GE.15.0) THEN
       IF(TEST.LT.0.002 .AND. TEST.GE.0.001) THEN
        Q1=-300.*TEST+1.81
       ENDIF
       IF(TEST.LT.0.0034 .AND. TEST.GE.0.002) THEN
        Q1=-114.2857143*TEST+1.438571429
       ENDIF
       IF(TEST.GE.0.0034)Q1=1.05
       IF(TEST.LT.0.0015 .AND. TEST.GE.0.001) THEN
        Q2=-500.*TEST+2.35
       ENDIF
       IF(TEST.LT.0.002 .AND. TEST.GE.0.0015) THEN
        Q2=-300.*TEST+2.05
       ENDIF
       IF(TEST.LT.0.0037 .AND. TEST.GE.0.002) THEN
        Q2=-147.0588*TEST+1.7441176
       ENDIF
       IF(TEST.LT.0.0058 .AND. TEST.GE.0.0037) THEN
        Q2=-66.666667*TEST+1.4466667
       ENDIF
       IF(TEST.GE.0.0034)Q2=1.06
C......CALCOLA IL VALORE Q IN FUNZIONE DEL VALORE DI ALFA
       DX=(Q2-Q1)/5.0
       Q=ALFA*DX+Q1
      ENDIF
C.....RETTA 2 E 3 CON ALFA COMPRESO TRA 20 E 25 GRADI
      IF(ALFA.LT.20.0 .AND. ALFA.GE.15.0) THEN
       IF(TEST.LT.0.0015 .AND. TEST.GE.0.001) THEN
        Q1=-500.*TEST+2.35
       ENDIF
       IF(TEST.LT.0.002 .AND. TEST.GE.0.0015) THEN
        Q1=-300.*TEST+2.05
       ENDIF
       IF(TEST.LT.0.0037 .AND. TEST.GE.0.002) THEN
        Q1=-147.0588*TEST+1.7441176
       ENDIF
       IF(TEST.LT.0.0058 .AND. TEST.GE.0.0037) THEN
        Q1=-66.666667*TEST+1.4466667
       ENDIF
       IF(TEST.GE.0.0034)Q1=1.06
       IF(TEST.LT.0.002 .AND. TEST.GT.0.001)THEN
        Q2=-440.*TEST+2.6
       ENDIF
       IF(TEST.LT.0.0036 .AND. TEST.GE.0.002)THEN
        Q2=-200.*TEST+2.12
       ENDIF
       IF(TEST.LT.0.005 .AND. TEST.GT.0.0036)THEN
        Q2=-100.*TEST+1.76
       ENDIF
       IF(TEST.LT.0.008 .AND. TEST.GT.0.005)THEN
        Q2=-50.*TEST+1.51
       ENDIF
       IF(TEST.GE.008)Q2=1.11
C......CALCOLA IL VALORE Q IN FUNZIONE DEL VALORE DI ALFA
       DX=(Q2-Q1)/5.0
       Q=ALFA*DX+Q1
      ENDIF
C.....RETTA 2 E 3 CON ALFA COMPRESO TRA 20 E 25 GRADI
      IF(ALFA.LT.20.0 .AND. ALFA.GE.15.0) THEN
       IF(TEST.LT.0.002 .AND. TEST.GT.0.001)THEN
        Q1=-440.*TEST+2.6
       ENDIF
       IF(TEST.LT.0.0036 .AND. TEST.GE.0.002)THEN
        Q1=-200.*TEST+2.12
       ENDIF
       IF(TEST.LT.0.005 .AND. TEST.GT.0.0036)THEN
        Q1=-100.*TEST+1.76
       ENDIF
       IF(TEST.LT.0.008 .AND. TEST.GT.0.005)THEN
        Q1=-50.*TEST+1.51
       ENDIF
       IF(TEST.GE.008)Q1=1.11
       IF(TEST.LT.0.003 .AND. TEST.GT.0.0015)THEN
        Q2=-300.*TEST+2.6
       ENDIF
       IF(TEST.LT.0.004 .AND. TEST.GT.0.003)THEN
        Q2=-170.*TEST+2.21
       ENDIF
       IF(TEST.LT.0.006 .AND. TEST.GT.0.004)THEN
        Q2=-90.*TEST+1.89
       ENDIF
       IF(TEST.LT.0.01 .AND. TEST.GT.0.006)THEN
        Q2=-47.5*TEST+1.635
       ENDIF
       IF(TEST.GE.0.01)Q2=1.16
C......CALCOLA IL VALORE Q IN FUNZIONE DEL VALORE DI ALFA
       DX=(Q2-Q1)/5.0
       Q=ALFA*DX+Q1
      ENDIF
C.....CALCOLA LO SPESSORE RICHIESTO DEL CONO/CILINDRO
      TR=Q*T
C.....CALCOLO DELLA LUNGHEZZA DEL RINFORZO SUL CILINDRO CON DIAM. MAGG.
      RC=(DD1+2.0*C1)*0.5
      RRLC=2.0*SQRT(TR*RC)
C.....CALCOLO DELLA LUNGHEZZA DEL RINFORZO SUL CONO ZONA DIAM. MAGG.
      RRL=2.0*SQRT(R*TR/COS(ALFA))
      T=TR
999   CONTINUE
      RETURN
      END
